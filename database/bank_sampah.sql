BEGIN;

-- =========================================================
-- 1. TABEL MASTER JENIS SAMPAH
-- =========================================================

CREATE TABLE jenis_sampah (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_jenis_sampah VARCHAR(100) NOT NULL UNIQUE,
    harga_per_kg NUMERIC(12,2) NOT NULL,
    keterangan TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT cek_harga_positif CHECK (harga_per_kg > 0)
);

-- =========================================================
-- 2. TABEL NASABAH
-- =========================================================

CREATE TABLE nasabah (
    id_nasabah INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_nasabah VARCHAR(100) NOT NULL,
    nik VARCHAR(20) UNIQUE,
    alamat TEXT,
    no_telepon VARCHAR(20),
    tanggal_daftar TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) DEFAULT 'aktif'
);

-- =========================================================
-- 3. TABEL PENGURUS
-- =========================================================

CREATE TABLE pengurus (
    id_pengurus INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_pengurus VARCHAR(100) NOT NULL,
    no_telepon VARCHAR(20),
    alamat TEXT,
    jabatan VARCHAR(50)
);

-- =========================================================
-- 4. TABEL TRANSAKSI BANK SAMPAH
--    nama_nasabah sudah tidak disimpan di sini.
--    Identitas nasabah diambil melalui JOIN menggunakan id_nasabah.
-- =========================================================

CREATE TABLE transaksi_bank_sampah (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_transaksi VARCHAR(30),
    id_nasabah INT NOT NULL,
    jenis_transaksi VARCHAR(20) NOT NULL,
    jenis_sampah_id INT,
    berat_kg NUMERIC(10,2),
    total_nilai NUMERIC(12,2) NOT NULL,
    tanggal_transaksi TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    keterangan TEXT,

    CONSTRAINT fk_transaksi_jenis_sampah
        FOREIGN KEY (jenis_sampah_id)
        REFERENCES jenis_sampah(id),

    CONSTRAINT fk_transaksi_nasabah
        FOREIGN KEY (id_nasabah)
        REFERENCES nasabah(id_nasabah),

    CONSTRAINT cek_jenis_transaksi
        CHECK (jenis_transaksi IN ('setoran', 'penarikan')),

    CONSTRAINT cek_total_nilai
        CHECK (total_nilai > 0),

    CONSTRAINT cek_detail_transaksi
        CHECK (
            (
                jenis_transaksi = 'setoran'
                AND jenis_sampah_id IS NOT NULL
                AND berat_kg > 0
            )
            OR
            (
                jenis_transaksi = 'penarikan'
                AND jenis_sampah_id IS NULL
                AND berat_kg IS NULL
            )
        )
);

-- =========================================================
-- 5. TABEL AKUN
--    Satu akun terhubung ke nasabah ATAU pengurus.
-- =========================================================

CREATE TABLE akun (
    id_akun INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_nasabah INT UNIQUE,
    id_pengurus INT UNIQUE,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    status_akun VARCHAR(20) DEFAULT 'aktif',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_akun_nasabah
        FOREIGN KEY (id_nasabah)
        REFERENCES nasabah(id_nasabah),

    CONSTRAINT fk_akun_pengurus
        FOREIGN KEY (id_pengurus)
        REFERENCES pengurus(id_pengurus),

    CONSTRAINT chk_akun_role
        CHECK (
            (role = 'nasabah' AND id_nasabah IS NOT NULL AND id_pengurus IS NULL)
            OR
            (role = 'pengurus' AND id_pengurus IS NOT NULL AND id_nasabah IS NULL)
        )
);

-- =========================================================
-- 6. TABEL DETAIL TRANSAKSI
--    Menyimpan beberapa jenis sampah dalam satu transaksi setoran.
-- =========================================================

CREATE TABLE detail_transaksi (
    id_detail INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaksi INT NOT NULL,
    id_jenis_sampah INT NOT NULL,
    berat_kg NUMERIC(10,2) NOT NULL,
    harga_per_kg NUMERIC(12,2) NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL,

    CONSTRAINT fk_detail_transaksi
        FOREIGN KEY (id_transaksi)
        REFERENCES transaksi_bank_sampah(id),

    CONSTRAINT fk_detail_jenis_sampah
        FOREIGN KEY (id_jenis_sampah)
        REFERENCES jenis_sampah(id),

    CONSTRAINT chk_detail_berat CHECK (berat_kg > 0),
    CONSTRAINT chk_detail_harga CHECK (harga_per_kg > 0),
    CONSTRAINT chk_detail_subtotal CHECK (subtotal >= 0)
);

-- =========================================================
-- 7. TABEL SALDO NASABAH
-- =========================================================

CREATE TABLE saldo_nasabah (
    id_saldo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_nasabah INT NOT NULL UNIQUE,
    saldo NUMERIC(14,2) NOT NULL DEFAULT 0,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_saldo_nasabah
        FOREIGN KEY (id_nasabah)
        REFERENCES nasabah(id_nasabah),

    CONSTRAINT chk_saldo CHECK (saldo >= 0)
);

-- =========================================================
-- 8. TABEL BUKTI TRANSAKSI
-- =========================================================

CREATE TABLE bukti_transaksi (
    id_bukti INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaksi INT NOT NULL,
    nama_file VARCHAR(255) NOT NULL,
    file_bukti TEXT NOT NULL,
    tipe_file VARCHAR(50),
    tanggal_upload TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_bukti_transaksi
        FOREIGN KEY (id_transaksi)
        REFERENCES transaksi_bank_sampah(id)
);

-- =========================================================
-- 9. TABEL NOTIFIKASI
-- =========================================================

CREATE TABLE notifikasi (
    id_notifikasi INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_nasabah INT NOT NULL,
    id_transaksi INT,
    judul VARCHAR(100) NOT NULL,
    pesan TEXT NOT NULL,
    status_baca BOOLEAN DEFAULT FALSE,
    tanggal_dibuat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_notifikasi_nasabah
        FOREIGN KEY (id_nasabah)
        REFERENCES nasabah(id_nasabah),

    CONSTRAINT fk_notifikasi_transaksi
        FOREIGN KEY (id_transaksi)
        REFERENCES transaksi_bank_sampah(id)
);

