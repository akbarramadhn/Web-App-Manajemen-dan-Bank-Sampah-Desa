-- Cek jumlah data per tabel
SELECT 'jenis_sampah' AS nama_tabel, COUNT(*) AS jumlah_data FROM jenis_sampah
UNION ALL SELECT 'nasabah', COUNT(*) FROM nasabah
UNION ALL SELECT 'pengurus', COUNT(*) FROM pengurus
UNION ALL SELECT 'akun', COUNT(*) FROM akun
UNION ALL SELECT 'transaksi_bank_sampah', COUNT(*) FROM transaksi_bank_sampah
UNION ALL SELECT 'detail_transaksi', COUNT(*) FROM detail_transaksi
UNION ALL SELECT 'saldo_nasabah', COUNT(*) FROM saldo_nasabah
UNION ALL SELECT 'bukti_transaksi', COUNT(*) FROM bukti_transaksi
UNION ALL SELECT 'notifikasi', COUNT(*) FROM notifikasi;

-- Cek transaksi dengan nama nasabah
SELECT
    t.id,
    t.kode_transaksi,
    n.nama_nasabah,
    t.jenis_transaksi,
    t.total_nilai,
    t.tanggal_transaksi
FROM transaksi_bank_sampah t
JOIN nasabah n ON n.id_nasabah = t.id_nasabah
ORDER BY t.id;

-- Cek saldo nasabah
SELECT
    n.id_nasabah,
    n.nama_nasabah,
    s.saldo
FROM nasabah n
JOIN saldo_nasabah s ON s.id_nasabah = n.id_nasabah
ORDER BY n.id_nasabah;